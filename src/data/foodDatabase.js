//        raw = gramos de alimento crudo que lleva cada gramo preparado (para precio y lista de compra).
//
// price: precio promedio en Uruguay, en pesos uruguayos (UYU).
//   uyu   → importe de referencia
//   per   → unidad de compra (kg, litro, maple 30, lata, pote…)
//   grams → gramos comestibles que trae esa unidad (permite calcular $U por gramo)
//   ref   → dónde se toma la referencia (feria, carnicería, supermercado)
